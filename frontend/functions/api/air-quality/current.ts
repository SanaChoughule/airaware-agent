// Cloudflare Pages Function: GET /api/air-quality/current & /api/air-quality/forecast
export async function onRequestGet(context: any) {
  const url = new URL(context.request.url);
  const lat = parseFloat(url.searchParams.get("latitude") || "19.0760");
  const lng = parseFloat(url.searchParams.get("longitude") || "72.8777");

  try {
    const openMeteoUrl = `https://air-quality-api.open-meteo.com/v1/air-quality?latitude=${lat.toFixed(
      4
    )}&longitude=${lng.toFixed(
      4
    )}&current=european_aqi,us_aqi,pm10,pm2_5,carbon_monoxide,nitrogen_dioxide,sulphur_dioxide,ozone&hourly=pm10,pm2_5,us_aqi`;

    const res = await fetch(openMeteoUrl);
    if (res.ok) {
      const data: any = await res.json();
      const current = data.current || {};

      let usAqi = current.us_aqi || 0;
      const pm25 = current.pm2_5 || 0;
      const pm10 = current.pm10 || 0;
      const co = current.carbon_monoxide || 0;
      const no2 = current.nitrogen_dioxide || 0;
      const so2 = current.sulphur_dioxide || 0;
      const o3 = current.ozone || 0;

      if (usAqi <= 0 && pm25 > 0) {
        usAqi = calculateAqiFromPm25(pm25);
      }
      if (usAqi <= 0) usAqi = 75;

      const category = getCategoryForAqi(usAqi);
      const healthRisk = getHealthRiskForAqi(usAqi);
      const dominant = determineDominant(pm25, pm10, o3, no2, so2);

      // Hourly Forecast
      const hourly = data.hourly || {};
      const times = hourly.time || [];
      const aqis = hourly.us_aqi || [];
      const pm25s = hourly.pm2_5 || [];

      const currentHour = new Date().getHours();
      const hourlyList = [];
      let lowestAqi = 999;
      let bestHourTime = "14:00";

      const count = Math.min(24, Math.max(1, times.length - currentHour));
      for (let i = 0; i < count; i++) {
        const idx = currentHour + i;
        if (idx >= times.length) break;

        const tStr = times[idx] || "";
        const timeLabel = tStr.includes("T") ? tStr.split("T")[1] : tStr;
        let hAqi = aqis[idx] || 0;
        const hPm25 = pm25s[idx] || 0;

        if (hAqi <= 0 && hPm25 > 0) hAqi = calculateAqiFromPm25(hPm25);
        if (hAqi <= 0) hAqi = usAqi;

        if (hAqi < lowestAqi) {
          lowestAqi = hAqi;
          bestHourTime = timeLabel;
        }

        hourlyList.push({
          time: timeLabel,
          aqi: hAqi,
          category: getCategoryForAqi(hAqi),
          pm25: round(hPm25),
          recommendedWindow: false,
        });
      }

      hourlyList.forEach((item) => {
        if (item.aqi === lowestAqi || item.aqi <= 50) {
          item.recommendedWindow = true;
        }
      });

      const responseObj = {
        latitude: lat,
        longitude: lng,
        locationName: `Active Position (${lat.toFixed(3)}°N, ${lng.toFixed(3)}°E)`,
        aqi: usAqi,
        category,
        healthRisk,
        dominantPollutant: dominant,
        summary: `Live satellite & atmospheric observation indicates an AQI of ${usAqi} (${category}) around this location. ${dominant} is the dominant particulate factor. ${
          usAqi > 150
            ? "Stagnation is trapping ground-level particles; sensitive individuals should restrict outdoor cardio."
            : "Atmospheric dispersion is favorable. Outdoor exercise and ventilation are viable during optimal daytime windows."
        }`,
        lastUpdated: new Date().toLocaleTimeString([], {
          hour: "2-digit",
          minute: "2-digit",
        }),
        simulated: false,
        pollutants: {
          "PM2.5": {
            name: "PM2.5",
            value: round(pm25),
            unit: "µg/m³",
            category: getPm25Category(pm25),
            percentOfStandard: Math.round((pm25 / 60) * 100),
            explanation:
              "Fine inhalable particles penetrating deep into bronchial passages and blood streams.",
          },
          PM10: {
            name: "PM10",
            value: round(pm10),
            unit: "µg/m³",
            category: getPm10Category(pm10),
            percentOfStandard: Math.round((pm10 / 100) * 100),
            explanation:
              "Inhalable road dust, pollen and construction particulate irritating upper airways.",
          },
          O3: {
            name: "O3",
            value: round(o3),
            unit: "µg/m³",
            category: "Good",
            percentOfStandard: Math.round((o3 / 100) * 100),
            explanation:
              "Tropospheric ozone generated by sunlight photochemical reaction with vehicular exhaust.",
          },
          NO2: {
            name: "NO2",
            value: round(no2),
            unit: "µg/m³",
            category: "Good",
            percentOfStandard: Math.round((no2 / 80) * 100),
            explanation:
              "Nitrogen dioxide largely emitted from internal combustion engines and diesel exhausts.",
          },
          SO2: {
            name: "SO2",
            value: round(so2),
            unit: "µg/m³",
            category: "Good",
            percentOfStandard: Math.round((so2 / 80) * 100),
            explanation:
              "Sulfur dioxide produced by thermal coal combustion and heavy industrial refineries.",
          },
          CO: {
            name: "CO",
            value: round(co / 1000),
            unit: "mg/m³",
            category: "Good",
            percentOfStandard: Math.round((co / 4000) * 100),
            explanation:
              "Carbon monoxide produced by incomplete combustion of petroleum and gas.",
          },
        },
        hourlyForecast: hourlyList,
        bestOutdoorWindow: `${bestHourTime} (Lowest diurnal exposure ~AQI ${lowestAqi})`,
      };

      return new Response(JSON.stringify(responseObj), {
        headers: {
          "Content-Type": "application/json",
          "Access-Control-Allow-Origin": "*",
        },
      });
    }
  } catch (err) {
    console.error("Open-Meteo fetch failed:", err);
  }

  // Fallback realistic response
  return new Response(
    JSON.stringify({
      latitude: lat,
      longitude: lng,
      locationName: `Region (${lat.toFixed(3)}°N, ${lng.toFixed(3)}°E)`,
      aqi: 114,
      category: "Moderate",
      healthRisk: "Moderate",
      dominantPollutant: "PM2.5",
      summary: "Air quality is currently in the moderate range. Sensitive individuals may experience mild respiratory symptoms.",
      lastUpdated: new Date().toLocaleTimeString(),
      simulated: true,
      pollutants: {},
      hourlyForecast: [],
      bestOutdoorWindow: "14:00 (Lowest diurnal exposure ~AQI 75)",
    }),
    {
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      },
    }
  );
}

function calculateAqiFromPm25(pm25: number) {
  if (pm25 <= 12.0) return Math.round((50.0 / 12.0) * pm25);
  if (pm25 <= 35.4) return 50 + Math.round((49.0 / 23.4) * (pm25 - 12.1));
  if (pm25 <= 55.4) return 100 + Math.round((49.0 / 20.0) * (pm25 - 35.5));
  if (pm25 <= 150.4) return 150 + Math.round((49.0 / 95.0) * (pm25 - 55.5));
  if (pm25 <= 250.4) return 200 + Math.round((99.0 / 100.0) * (pm25 - 150.5));
  return 300 + Math.round(pm25 - 250.5);
}

function getCategoryForAqi(aqi: number) {
  if (aqi <= 50) return "Good";
  if (aqi <= 100) return "Moderate";
  if (aqi <= 200) return "Poor";
  if (aqi <= 300) return "Very Poor";
  return "Severe";
}

function getHealthRiskForAqi(aqi: number) {
  if (aqi <= 50) return "Low";
  if (aqi <= 100) return "Moderate";
  if (aqi <= 200) return "High";
  if (aqi <= 300) return "Very High";
  return "Hazardous";
}

function determineDominant(
  pm25: number,
  pm10: number,
  o3: number,
  no2: number,
  so2: number
) {
  const s25 = pm25 / 30;
  const s10 = pm10 / 50;
  const so = o3 / 100;
  const sn = no2 / 40;
  const ss = so2 / 40;

  const max = Math.max(s25, s10, so, sn, ss);
  if (max === s25) return "PM2.5";
  if (max === s10) return "PM10";
  if (max === so) return "O3";
  if (max === sn) return "NO2";
  return "SO2";
}

function getPm25Category(pm25: number) {
  if (pm25 <= 15) return "Good";
  if (pm25 <= 35) return "Moderate";
  if (pm25 <= 75) return "Poor";
  if (pm25 <= 150) return "Very Poor";
  return "Severe";
}

function getPm10Category(pm10: number) {
  if (pm10 <= 50) return "Good";
  if (pm10 <= 100) return "Moderate";
  if (pm10 <= 150) return "Poor";
  if (pm10 <= 250) return "Very Poor";
  return "Severe";
}

function round(val: number) {
  return Math.round(val * 10) / 10;
}
