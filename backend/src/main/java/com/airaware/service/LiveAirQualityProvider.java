package com.airaware.service;

import com.airaware.model.AirQualityData;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.web.reactive.function.client.WebClient;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.*;

@Service
public class LiveAirQualityProvider implements AirQualityProvider {
    private static final Logger log = LoggerFactory.getLogger(LiveAirQualityProvider.class);

    private final WebClient webClient;
    private final ObjectMapper objectMapper;
    private final SimulatedAirQualityProvider fallbackProvider;

    public LiveAirQualityProvider(ObjectMapper objectMapper, SimulatedAirQualityProvider fallbackProvider) {
        this.objectMapper = objectMapper;
        this.fallbackProvider = fallbackProvider;
        this.webClient = WebClient.builder()
                .codecs(configurer -> configurer.defaultCodecs().maxInMemorySize(2 * 1024 * 1024))
                .build();
    }

    @Override
    public String getProviderName() {
        return "Open-Meteo Global Environmental Satellite & Station Feeds";
    }

    @Override
    public AirQualityData getCurrentAirQuality(double latitude, double longitude) {
        try {
            String url = String.format(
                    Locale.US,
                    "https://air-quality-api.open-meteo.com/v1/air-quality?latitude=%.4f&longitude=%.4f&current=european_aqi,us_aqi,pm10,pm2_5,carbon_monoxide,nitrogen_dioxide,sulphur_dioxide,ozone&hourly=pm10,pm2_5,us_aqi",
                    latitude, longitude
            );

            String responseBody = webClient.get()
                    .uri(url)
                    .retrieve()
                    .bodyToMono(String.class)
                    .block();

            if (responseBody != null && !responseBody.isEmpty()) {
                JsonNode root = objectMapper.readTree(responseBody);
                JsonNode current = root.path("current");
                if (!current.isMissingNode()) {
                    AirQualityData data = new AirQualityData();
                    data.setLatitude(latitude);
                    data.setLongitude(longitude);
                    data.setSimulated(false); // Real live atmospheric observation!
                    data.setLastUpdated(LocalDateTime.now().format(DateTimeFormatter.ofPattern("hh:mm a, dd MMM yyyy")));

                    int usAqi = current.path("us_aqi").asInt(0);
                    double pm25 = current.path("pm2_5").asDouble(0.0);
                    double pm10 = current.path("pm10").asDouble(0.0);
                    double co = current.path("carbon_monoxide").asDouble(0.0);
                    double no2 = current.path("nitrogen_dioxide").asDouble(0.0);
                    double so2 = current.path("sulphur_dioxide").asDouble(0.0);
                    double o3 = current.path("ozone").asDouble(0.0);

                    // If US AQI is missing or 0, compute EPA AQI from PM2.5
                    if (usAqi <= 0 && pm25 > 0) {
                        usAqi = calculateAqiFromPm25(pm25);
                    }
                    if (usAqi <= 0) {
                        usAqi = 45; // baseline clean
                    }

                    data.setAqi(usAqi);
                    data.setCategory(SimulatedAirQualityProvider.getCategoryForAqi(usAqi));
                    data.setHealthRisk(SimulatedAirQualityProvider.getHealthRiskForAqi(usAqi));

                    // Determine dominant pollutant
                    String dominant = determineDominant(pm25, pm10, o3, no2, so2);
                    data.setDominantPollutant(dominant);

                    // Build measured pollutants map
                    Map<String, AirQualityData.PollutantDetail> pollutants = new LinkedHashMap<>();
                    pollutants.put("PM2.5", new AirQualityData.PollutantDetail(
                            "PM2.5", round(pm25), "µg/m³", getPm25Category(pm25), (int)((pm25 / 60.0) * 100),
                            "Fine inhalable particles penetrating deep into bronchial passages and blood streams."
                    ));
                    pollutants.put("PM10", new AirQualityData.PollutantDetail(
                            "PM10", round(pm10), "µg/m³", getPm10Category(pm10), (int)((pm10 / 100.0) * 100),
                            "Inhalable road dust, pollen and construction particulate irritating upper airways."
                    ));
                    pollutants.put("O3", new AirQualityData.PollutantDetail(
                            "O3", round(o3), "µg/m³", "Good", (int)((o3 / 100.0) * 100),
                            "Tropospheric ozone generated by sunlight photochemical reaction with vehicular exhaust."
                    ));
                    pollutants.put("NO2", new AirQualityData.PollutantDetail(
                            "NO2", round(no2), "µg/m³", "Good", (int)((no2 / 80.0) * 100),
                            "Nitrogen dioxide largely emitted from internal combustion engines and diesel exhausts."
                    ));
                    pollutants.put("SO2", new AirQualityData.PollutantDetail(
                            "SO2", round(so2), "µg/m³", "Good", (int)((so2 / 80.0) * 100),
                            "Sulfur dioxide produced by thermal coal combustion and heavy industrial refineries."
                    ));
                    pollutants.put("CO", new AirQualityData.PollutantDetail(
                            "CO", round(co / 1000.0), "mg/m³", "Good", (int)((co / 4000.0) * 100),
                            "Carbon monoxide produced by incomplete combustion of petroleum and gas."
                    ));
                    data.setPollutants(pollutants);

                    // Parse hourly forecast from Open-Meteo
                    JsonNode hourlyNode = root.path("hourly");
                    List<AirQualityData.HourlyForecast> hourlyList = new ArrayList<>();
                    int bestHour = -1;
                    int lowestAqi = Integer.MAX_VALUE;

                    if (!hourlyNode.isMissingNode() && hourlyNode.path("time").isArray()) {
                        JsonNode times = hourlyNode.path("time");
                        JsonNode aqis = hourlyNode.path("us_aqi");
                        JsonNode pm25s = hourlyNode.path("pm2_5");

                        int currentHourIdx = LocalDateTime.now().getHour();
                        int count = Math.min(24, times.size() - currentHourIdx);
                        if (count <= 0) count = Math.min(24, times.size());
                        int startIdx = Math.max(0, currentHourIdx);

                        for (int i = 0; i < count; i++) {
                            int idx = startIdx + i;
                            if (idx >= times.size()) break;
                            String tStr = times.get(idx).asText(); // e.g. "2026-11-24T14:00"
                            String timeLabel = tStr.contains("T") ? tStr.split("T")[1] : tStr;

                            int hAqi = aqis.has(idx) ? aqis.get(idx).asInt() : 0;
                            double hPm25 = pm25s.has(idx) ? pm25s.get(idx).asDouble() : 0.0;
                            if (hAqi <= 0 && hPm25 > 0) {
                                hAqi = calculateAqiFromPm25(hPm25);
                            }
                            if (hAqi <= 0) hAqi = usAqi;

                            if (hAqi < lowestAqi) {
                                lowestAqi = hAqi;
                                bestHour = i;
                            }

                            hourlyList.add(new AirQualityData.HourlyForecast(
                                    timeLabel,
                                    hAqi,
                                    SimulatedAirQualityProvider.getCategoryForAqi(hAqi),
                                    round(hPm25),
                                    false
                            ));
                        }

                        // Mark recommended window
                        for (int i = 0; i < hourlyList.size(); i++) {
                            if (hourlyList.get(i).getAqi() == lowestAqi || hourlyList.get(i).getAqi() <= 50) {
                                hourlyList.get(i).setRecommendedWindow(true);
                            }
                        }
                    }

                    if (hourlyList.isEmpty()) {
                        data.setHourlyForecast(fallbackProvider.getCurrentAirQuality(latitude, longitude).getHourlyForecast());
                        data.setBestOutdoorWindow(fallbackProvider.getCurrentAirQuality(latitude, longitude).getBestOutdoorWindow());
                    } else {
                        data.setHourlyForecast(hourlyList);
                        String bestTime = bestHour >= 0 && bestHour < hourlyList.size() ? hourlyList.get(bestHour).getTime() : "14:00";
                        data.setBestOutdoorWindow(bestTime + " (Lowest diurnal exposure ~AQI " + lowestAqi + ")");
                    }

                    data.setSummary(String.format(
                            "Live satellite & atmospheric observation indicates an AQI of %d (%s) around this location. %s is the dominant particulate factor. %s",
                            usAqi,
                            data.getCategory(),
                            dominant,
                            usAqi > 150
                                    ? "Stagnation is trapping ground-level particles; sensitive individuals should restrict outdoor cardio."
                                    : "Atmospheric dispersion is favorable. Outdoor exercise and ventilation are viable during optimal daytime windows."
                    ));

                    return data;
                }
            }
        } catch (Exception ex) {
            log.warn("Live Open-Meteo air quality fetch failed for ({}, {}): {}. Falling back to deterministic model.", latitude, longitude, ex.getMessage());
        }

        return fallbackProvider.getCurrentAirQuality(latitude, longitude);
    }

    @Override
    public AirQualityData getForecast(double latitude, double longitude) {
        return getCurrentAirQuality(latitude, longitude);
    }

    private int calculateAqiFromPm25(double pm25) {
        if (pm25 <= 12.0) return (int) ((50.0 / 12.0) * pm25);
        if (pm25 <= 35.4) return 50 + (int) ((49.0 / 23.4) * (pm25 - 12.1));
        if (pm25 <= 55.4) return 100 + (int) ((49.0 / 20.0) * (pm25 - 35.5));
        if (pm25 <= 150.4) return 150 + (int) ((49.0 / 95.0) * (pm25 - 55.5));
        if (pm25 <= 250.4) return 200 + (int) ((99.0 / 100.0) * (pm25 - 150.5));
        return 300 + (int) (pm25 - 250.5);
    }

    private String determineDominant(double pm25, double pm10, double o3, double no2, double so2) {
        double pm25Score = pm25 / 30.0;
        double pm10Score = pm10 / 50.0;
        double o3Score = o3 / 100.0;
        double no2Score = no2 / 40.0;
        double so2Score = so2 / 40.0;

        double max = Math.max(pm25Score, Math.max(pm10Score, Math.max(o3Score, Math.max(no2Score, so2Score))));
        if (max == pm25Score) return "PM2.5";
        if (max == pm10Score) return "PM10";
        if (max == o3Score) return "O3";
        if (max == no2Score) return "NO2";
        return "SO2";
    }

    private String getPm25Category(double pm25) {
        if (pm25 <= 15) return "Good";
        if (pm25 <= 35) return "Moderate";
        if (pm25 <= 75) return "Poor";
        if (pm25 <= 150) return "Very Poor";
        return "Severe";
    }

    private String getPm10Category(double pm10) {
        if (pm10 <= 50) return "Good";
        if (pm10 <= 100) return "Moderate";
        if (pm10 <= 150) return "Poor";
        if (pm10 <= 250) return "Very Poor";
        return "Severe";
    }

    private double round(double val) {
        return Math.round(val * 10.0) / 10.0;
    }
}
